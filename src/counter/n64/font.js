export const GLYPH = { width: 5, height: 7, gap: 1 };

export const hasGlyph = (char) => Object.hasOwn(ROWS, char);

export function textWidth(text, scale = 1) {
  return text.length ? (text.length * (GLYPH.width + GLYPH.gap) - GLYPH.gap) * scale : 0;
}

// Calls dot(x, y) for every lit dot of `text` at `scale`, top-left at (x0, y0).
export function eachDot(text, x0, y0, scale, dot) {
  [...text].forEach((char, index) => {
    const rows = ROWS[char];
    if (!rows) throw new Error(`sign font has no glyph for ${JSON.stringify(char)}`);
    const left = x0 + index * (GLYPH.width + GLYPH.gap) * scale;
    rows.forEach((row, y) => {
      [...row].forEach((bit, x) => {
        if (bit !== "#") return;
        for (let sy = 0; sy < scale; sy += 1) for (let sx = 0; sx < scale; sx += 1) dot(left + x * scale + sx, y0 + y * scale + sy);
      });
    });
  });
}
