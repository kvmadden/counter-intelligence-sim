const CHW = 6; // advance: 5px glyph + 1px spacing

// ---- layout helpers -------------------------------------------------------
function textW(str, scale) { scale = scale || 1; return str.length * CHW * scale - scale; }

// Force a single line to fit maxW pixels: truncate with ".." if needed.
function fitLine(str, maxW, scale) {
  scale = scale || 1;
  const chars = Math.max(1, Math.floor((maxW + scale) / (CHW * scale)));
  if (str.length <= chars) return str;
  return str.slice(0, chars - 2) + '..';
}

// Word-wrap into lines that fit maxW, then hard-fit each line. Returns up to maxLines lines.
function wrapText(str, maxW, scale, maxLines) {
  scale = scale || 1;
  const words = str.toUpperCase().split(/\s+/).filter(Boolean);
  const lines = [];
  let cur = '';
  for (const w of words) {
    const test = cur ? cur + ' ' + w : w;
    if (testW(test, scale) <= maxW) cur = test;
    else {
      if (cur) lines.push(cur);
      cur = w.length > 12 ? w.slice(0, 12) + '..' : w; // absurd word guard
    }
  }
  if (cur) lines.push(cur);
  const out = [];
  for (let i = 0; i < Math.min(lines.length, maxLines || 2); i++) out.push(fitLine(lines[i], maxW, scale));
  return out;
}
function testW(str, scale) { return textW(str, scale); }

export { FONT, CHW, textW, fitLine, wrapText };
