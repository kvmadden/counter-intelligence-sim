// Writes docs/claims/CLAIM-SUPPORT-SHEET.md and src/counter/claim-status.js from the
// committed ledger, CDC passages, Kevin's decisions (support-reviews.json) and bound
// drafts (pending-drafts.json). The sheet puts only claims still waiting for Kevin at
// the top, each with the claim, the lines that say it, the exact CDC quote and the
// link the player sees. The runtime module carries one status per claim to the debrief.
// Offline, from committed files only. Run: node scripts/claim-sheet.mjs
import fs from 'node:fs'
import path from 'node:path'
import { CLAIMS } from '../src/counter/claims.js'
import { root, reviewSheet } from './claim-proof.mjs'

const reviews = JSON.parse(fs.readFileSync(path.join(root, 'docs/claims/support-reviews.json'), 'utf8'))
const rows = reviewSheet()
const labelOf = row => row.status === 'approved' ? { label: 'Pharmacist approved', reviewedOn: row.review.reviewedOn } : { label: 'Pharmacist review pending', reviewedOn: null }
export const statusModule = () => [
  '// Generated by scripts/claim-sheet.mjs from docs/claims. Do not edit by hand.',
  '// One review status per claim for the debrief. Only Kevin\'s bound approvals read approved.',
  `export const CLAIM_STATUS = Object.freeze({`,
  ...rows.map(row => `  ${JSON.stringify(row.id)}: Object.freeze(${JSON.stringify({ status: row.status, ...labelOf(row) })}),`),
  '});',
  '',
].join('\n')

const lineRows = row => [...new Set(row.uses.filter(use => /choices\[\d+\]\.label$/.test(use.location)).map(use => use.text))]
const quote = text => text.trim().split('\n').map(line => `> ${line.trim()}`).join('\n>\n')
const pending = rows.filter(row => row.status !== 'approved')
const approved = rows.filter(row => row.status === 'approved')
const removed = Object.entries(reviews).filter(([id, review]) => review.decision === 'removed' && !CLAIMS[id])

const out = [
  '# Claim support sheet',
  '',
  `Kevin Madden, PharmD reviewed all ${Object.keys(reviews).length} claims on the previous sheet on 2026-11-01. His decisions, notes and the exact content each one covers are recorded in [support-reviews.json](support-reviews.json). ${approved.length} claims are approved and unchanged. ${pending.length} wait for his second look below. ${removed.length} were removed at his request.`,
  '',
  'Each pending block shows what Kevin asked for, what changed, the claim, the pharmacist lines that rely on it, the exact CDC passage retrieved on the date shown, and the link the player can open from the debrief. Check one box per claim. Record the decision in `support-reviews.json` (see [REVIEW.md](REVIEW.md)), then regenerate.',
  '',
  'Generated by `node scripts/claim-sheet.mjs`. Do not edit by hand except to tick boxes and add notes.',
  '',
  `## Pending Kevin's second look (${pending.length})`,
  '',
]
for (const row of pending) {
  const p = row.evidence ?? {}
  const said = lineRows(row).map(text => `- "${text}"`)
  out.push(`### ${row.id}`, '', `**Status:** ${row.status}`, '')
  if (row.review?.notes) out.push(`**Kevin's note (${row.review.decision}, ${row.review.reviewedOn}):** ${row.review.notes}`, '')
  if (row.draft?.change) out.push(`**What changed:** ${row.draft.change}`, '')
  out.push(`**Claim:** ${row.claim.text}`, '')
  out.push('**Pharmacist lines that use it:**', '', ...(said.length ? said : ['- none found']), '')
  out.push(`**CDC quote** (retrieved ${p.retrievedOn ?? 'not retrieved'}):`, '', p.passage ? quote(p.passage) : '> No passage captured.', '')
  out.push(`**Link in the game:** <${row.claim.source.url}>`)
  if (p.url && p.url !== row.claim.source.url) out.push('', `**Warning:** that link now leads to <${p.url}>, which says something different. Check the claim against the current page.`)
  if (row.claim.volatile) out.push('', '**Volatile:** this guidance changes often. Re-check before each season.')
  out.push('', '- [ ] Approve', '- [ ] Flag', '', 'Notes:', '', '---', '')
}
out.push(`## Approved by Kevin (${approved.length})`, '', 'Each approval is bound to the claim, its CDC quote and every dialogue use. Any later change to those reads `changed` and returns the claim to this sheet.', '', '| Claim | Decision | Reviewed | CDC page |', '| --- | --- | --- | --- |')
for (const row of approved) out.push(`| ${row.id} | approved | ${row.review.reviewedOn} | <${row.claim.source.url}> |`)
out.push('', `## Removed (${removed.length})`, '', 'Removed on 2026-11-01 at Kevin\'s request, with every line, branch, source and test that relied on them. The decision records stay in `support-reviews.json`.', '')
for (const [id, review] of removed) out.push(`- ${id}: ${review.notes}`)
out.push('')

if (process.argv[1] && path.resolve(process.argv[1]) === path.resolve(new URL(import.meta.url).pathname)) {
  fs.writeFileSync(path.join(root, 'docs/claims/CLAIM-SUPPORT-SHEET.md'), out.join('\n'))
  fs.writeFileSync(path.join(root, 'src/counter/claim-status.js'), statusModule())
  console.log(`claim-sheet: ${rows.length} claims, ${approved.length} approved, ${pending.length} pending, ${removed.length} removed`)
}
