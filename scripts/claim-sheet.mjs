// Writes docs/claims/CLAIM-SUPPORT-SHEET.md: one block per claim with the claim,
// the pharmacist lines that say it, the exact CDC quote, the link the player sees,
// and empty Approve / Flag boxes for Kevin. Offline, from committed files only.
// Run: node scripts/claim-sheet.mjs
import fs from 'node:fs'
import path from 'node:path'
import { CLAIMS } from '../src/counter/claims.js'
import { root, inventory } from './claim-proof.mjs'

const passages = JSON.parse(fs.readFileSync(path.join(root, 'docs/claims/passages.json'), 'utf8'))
const reviews = JSON.parse(fs.readFileSync(path.join(root, 'docs/claims/support-reviews.json'), 'utf8'))
const lines = inventory().filter(row => /choices\[\d+\]\.label$/.test(row.location))

const quote = text => text.trim().split('\n').map(line => `> ${line.trim()}`).join('\n>\n')
const out = [
  '# Claim support sheet',
  '',
  'For clinical review by Kevin Madden, PharmD. Review is pending. Nothing below is approved until Kevin marks it.',
  '',
  'Each block shows the claim, the pharmacist lines in the game that rely on it, the exact CDC passage retrieved on the date shown, and the link the player can open from the debrief. Check one box per claim. Record the decision in `support-reviews.json` (see [REVIEW.md](REVIEW.md)) so the build and the UI pick it up.',
  '',
  'Generated by `node scripts/claim-sheet.mjs`. Do not edit by hand except to tick boxes and add notes.',
  '',
]
for (const [id, claim] of Object.entries(CLAIMS)) {
  const p = passages[id] ?? {}
  const said = [...new Set(lines.filter(row => row.claims.includes(id)).map(row => row.text))].map(text => `- "${text}"`)
  const decision = reviews[id]?.decision ?? 'pending'
  out.push(`## ${id}`, '', `**Claim:** ${claim.text}`, '')
  out.push('**Pharmacist lines that use it:**', '', ...(said.length ? said : ['- none found']), '')
  out.push(`**CDC quote** (retrieved ${p.retrievedOn ?? 'not retrieved'}):`, '', p.passage ? quote(p.passage) : '> No passage captured.', '')
  out.push(`**Link in the game:** <${claim.source.url}>`)
  if (p.url && p.url !== claim.source.url) out.push('', `**Warning:** that link now leads to <${p.url}>, which says something different. Check the claim against the current page.`)
  if (claim.volatile) out.push('', '**Volatile:** this guidance changes often. Re-check before each season.')
  out.push('', `**Decision:** ${decision}`, '', '- [ ] Approve', '- [ ] Flag', '', 'Notes:', '', '---', '')
}
fs.writeFileSync(path.join(root, 'docs/claims/CLAIM-SUPPORT-SHEET.md'), out.join('\n'))
console.log(`claim-sheet: ${Object.keys(CLAIMS).length} claims written`)
